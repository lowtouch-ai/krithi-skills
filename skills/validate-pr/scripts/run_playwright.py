#!/usr/bin/env python3
"""Run the Playwright tests against the launched app and collect the evidence into the run folder (never the repo).

Every execution forces evidence on, whatever the repository's config says: a screenshot and a trace for every test,
video kept on failure, no retries (a flaky pass must not hide a defect), no webServer (the app was started by
app_runner.py, so its logs are captured), and all output written under the run folder:

  results/exec-<k>-<label>/   raw report (playwright-report.json or junit.xml), runner output, test-output/
  screenshots/exec-<k>/       <TC>__<test>__<project>__<n>.png      (failures and checkpoints)
  traces/exec-<k>/            <TC>__<test>__<project>.zip (+ videos)  open with: npx playwright show-trace <zip>
  logs/browser/exec-<k>/      console errors and page errors captured by the validate-pr fixture
  results/summary.json        every test case, latest execution wins; earlier executions are kept in "executions"
  report/playwright-html/     Playwright's HTML report of the latest execution (node runner)

Node runner: a wrapper config next to the repository's playwright.config (or --config) extends it with the overrides
above and is deleted afterwards; it is never staged. Python runner (pytest-playwright): the same through CLI flags.

Usage:
  run_playwright.py run --run D --cwd W --base-url URL [--runner node|python] [--config PATH] [--test-dir DIR]
                        [--project chromium] [--grep "TC-03|TC-07"] [--label initial] [--timeout 1800] [specs ...]
  run_playwright.py summary --run D [--markdown] [--link-prefix ../]   # links relative to report/ by default

Exit codes: 0 executed (whether tests passed or failed), 2 usage error, 4 the runner could not execute tests at all.
"""
import argparse, base64, hashlib, json, os, re, shutil, subprocess, sys, time
import xml.etree.ElementTree as ET  # parses only the junit.xml pytest just wrote in the run folder
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import clean_env, load_meta, log_event, merge_meta, now, out, rel, run, run_dir  # noqa: E402

TC_RE = re.compile(r"\b(TC-\d{1,4})\b")
ANSI = re.compile(r"\x1b\[[0-9;]*m")
HINTS = [  # (pattern in the error, likely class) -- a starting point only; SKILL.md step 6 confirms each failure
    (r"ERR_CONNECTION_REFUSED|ECONNREFUSED|ERR_NAME_NOT_RESOLVED|net::ERR_|Executable doesn't exist|browserType\.launch", "environment"),
    (r"strict mode violation|resolved to \d+ elements|Cannot find module|SyntaxError|is not a function|ReferenceError|"
     r"fixture .* not found|Unknown fixture|TypeError: Cannot read|No elements found for include", "test-automation"),
    # An assertion that compared a real value (the element was found) before a generic timeout pattern can claim it
    (r"Expected[: ].*Received|AssertionError|assert ", "application (assertion failed: confirm against the requirement)"),
    (r"Test timeout of \d+ms exceeded|waiting for (locator|getBy)|locator\.\w+: Timeout|element\(s\) not found",
     "application-or-test (element never appeared: check the screenshot and trace)"),
]
RUNNER_HINTS = [  # runner output when no tests executed -> what to do
    (r"Project\(s\) .* not found", "the --project name is not defined in the repository's config; omit --project or use one it defines"),
    (r"Executable doesn't exist|Please run the following command to download new browsers", "browsers missing: npx playwright install chromium"),
    (r"Cannot find module '@playwright/test'|could not determine executable to run", "@playwright/test is not installed in the worktree"),
    (r"No tests found", "no test matched: check testDir, --grep and the spec paths"),
]


def slug(s, n=60):
    return re.sub(r"[^A-Za-z0-9]+", "-", s).strip("-")[:n] or "test"


def hint(msg):
    for pat, cls in HINTS:
        if re.search(pat, msg or "", re.I | re.S):
            return cls
    return "unclassified"


def next_exec(d, label):
    k = 1 + len([p for p in (d / "results").glob("exec-*") if p.is_dir()])
    return k, f"exec-{k:02d}-{slug(label, 30)}"


WRAPPER = """// Generated by validate-pr for one execution and deleted afterwards. Never commit this file.
import {{ defineConfig }} from '@playwright/test';
{import_line}
const b: any = {base_expr};
export default defineConfig({{
  ...b,
  {test_dir}
  outputDir: {output},
  retries: 0,
  reporter: [['list'], ['json', {{ outputFile: {json_out} }}], ['html', {{ outputFolder: {html_out}, open: 'never' }}]],
  webServer: undefined,
  use: {{ ...(b.use || {{}}), baseURL: {base_url}, screenshot: 'on', trace: 'on', video: 'retain-on-failure' }},
}});
"""


def node_run(a, d, wt, exec_dir, label_dir):
    cfg = Path(a.config) if a.config else next((wt / f"playwright.config.{e}" for e in ("ts", "mts", "js", "mjs", "cjs")
                                                if (wt / f"playwright.config.{e}").is_file()), None)
    if cfg and not cfg.is_absolute():
        cfg = wt / cfg
    where = cfg.parent if cfg else wt / (Path(a.test_dir).parent if a.test_dir else ".")
    wrapper = where / ".validate-pr.playwright.config.ts"
    j = json.dumps
    test_dir = f"testDir: {j(str((wt / a.test_dir).resolve()))}," if a.test_dir else ""
    wrapper.write_text(WRAPPER.format(
        import_line=f"import base from './{cfg.name}';" if cfg else "",
        base_expr="(base as any) ?? {}" if cfg else "{}",
        test_dir=test_dir, output=j(str(exec_dir / "test-output")), json_out=j(str(exec_dir / "playwright-report.json")),
        html_out=j(str(d / "report" / "playwright-html")), base_url=j(a.base_url)), encoding="utf-8")
    cmd = ["npx", "--no-install", "playwright", "test", "-c", str(wrapper)]
    for p in a.project or []:
        cmd += ["--project", p]
    if a.grep:
        cmd += ["--grep", a.grep]
    cmd += a.specs or []
    env = clean_env({"BASE_URL": a.base_url, "PLAYWRIGHT_HTML_OPEN": "never", "CI": "1",
                     "VALIDATE_PR_CONSOLE_DIR": str(label_dir["browser"]), "FORCE_COLOR": "0"})
    try:
        return cmd, *execute(cmd, wt, env, exec_dir, a.timeout)
    finally:
        wrapper.unlink(missing_ok=True)


def python_run(a, d, wt, exec_dir, label_dir):
    cmd = [sys.executable if a.python is None else a.python, "-m", "pytest", "-p", "no:cacheprovider", "--base-url", a.base_url,
           "--tracing", "on", "--screenshot", "on", "--video", "retain-on-failure", "--output", str(exec_dir / "test-output"),
           f"--junitxml={exec_dir / 'junit.xml'}", "-rA"]
    for p in a.project or []:
        cmd += ["--browser", p]
    if a.grep:
        cmd += ["-k", a.grep.replace("|", " or ")]
    cmd += a.specs or ([a.test_dir] if a.test_dir else [])
    env = clean_env({"BASE_URL": a.base_url, "VALIDATE_PR_CONSOLE_DIR": str(label_dir["browser"]),
                     "VALIDATE_PR_SCREENSHOT_DIR": str(d / "screenshots" / exec_dir.name.split("-")[0] + "-" + exec_dir.name.split("-")[1])})
    return cmd, *execute(cmd, wt, env, exec_dir, a.timeout)


def execute(cmd, cwd, env, exec_dir, timeout):
    log = exec_dir / "runner-output.log"
    t0 = time.time()
    with log.open("w", encoding="utf-8") as f:
        f.write(f"# {now()}  cwd={cwd}\n# $ {' '.join(cmd)}\n\n")
        f.flush()
        try:
            code = subprocess.run(cmd, cwd=cwd, env=env, stdout=f, stderr=subprocess.STDOUT, timeout=timeout).returncode
        except subprocess.TimeoutExpired:
            code = 124
        except FileNotFoundError as e:
            code = 127
            f.write(f"command not found: {e.filename}\n")
    return code, round(time.time() - t0, 1), log


def save_attachment(att, dest_dir, base, n):
    dest_dir.mkdir(parents=True, exist_ok=True)
    ext = {"image/png": ".png", "image/jpeg": ".jpg", "application/zip": ".zip", "video/webm": ".webm",
           "application/json": ".json", "text/plain": ".txt"}.get(att.get("contentType"), "")
    name = f"{base}__{slug(att.get('name', 'attachment'), 30)}__{n}{ext}"
    dest = dest_dir / name
    if att.get("path") and Path(att["path"]).is_file():
        shutil.copyfile(att["path"], dest)
    elif att.get("body") is not None:
        body = att["body"]
        try:
            dest.write_bytes(base64.b64decode(body, validate=True))
        except (ValueError, TypeError):
            dest.write_text(body if isinstance(body, str) else json.dumps(body), encoding="utf-8")
    else:
        return None
    return dest


def walk_suites(suites, titles=()):
    for s in suites or []:
        t = titles + ((s.get("title"),) if s.get("title") and not s.get("title", "").endswith((".ts", ".js", ".mjs", ".tsx")) else ())
        for spec in s.get("specs") or []:
            yield t, spec, s.get("file")
        yield from walk_suites(s.get("suites"), t)


def collect_node(d, exec_dir, k):
    rp = exec_dir / "playwright-report.json"
    if not rp.is_file():
        return None, ["no JSON report was written: the runner did not start (see runner-output.log)"]
    rep = json.loads(rp.read_text(encoding="utf-8"))
    tests, errors = [], [ANSI.sub("", e.get("message", "")) for e in rep.get("errors") or []]
    for titles, spec, sfile in walk_suites(rep.get("suites")):
        for t in spec.get("tests") or []:
            res = (t.get("results") or [{}])[-1]
            full = " › ".join(titles + (spec.get("title", ""),))
            m = TC_RE.search(full)
            tc = m.group(1) if m else None
            st = t.get("status")
            outcome = {"expected": "passed", "flaky": "flaky", "skipped": "skipped"}.get(st) or \
                ("blocked" if res.get("status") == "interrupted" else "failed")
            msg = ANSI.sub("", "\n".join(e.get("message", "") for e in (res.get("errors") or ([res["error"]] if res.get("error") else []))))
            base = f"{tc or 'NO-TC'}__{slug(spec.get('title', ''), 40)}__{slug(t.get('projectName') or 'default', 15)}"
            ev = {"screenshots": [], "traces": [], "videos": [], "browser_logs": [], "other": []}
            for n, att in enumerate(res.get("attachments") or [], 1):
                ctype, name = att.get("contentType", ""), att.get("name", "")
                if ctype.startswith("image/"):
                    dst, key = d / "screenshots" / f"exec-{k:02d}", "screenshots"
                elif name == "trace" or ctype == "application/zip":
                    dst, key = d / "traces" / f"exec-{k:02d}", "traces"
                elif ctype.startswith("video/"):
                    dst, key = d / "traces" / f"exec-{k:02d}", "videos"
                elif "console" in name or "page-error" in name or "browser" in name:
                    dst, key = d / "logs" / "browser" / f"exec-{k:02d}", "browser_logs"
                else:
                    dst, key = d / "results" / exec_dir.name / "attachments", "other"
                p = save_attachment(att, dst, base, n)
                if p:
                    ev[key].append(rel(d, p))
            tests.append({"test_case": tc, "title": full, "file": spec.get("file") or sfile, "line": spec.get("line"),
                          "project": t.get("projectName"), "outcome": outcome, "runner_status": res.get("status"),
                          "duration_ms": res.get("duration"), "error": msg[:4000] or None,
                          "failure_hint": hint(msg) if outcome in ("failed", "blocked") else None,
                          "annotations": t.get("annotations") or [], "evidence": ev})
    return tests, errors


def collect_python(d, exec_dir, k):
    jx = exec_dir / "junit.xml"
    if not jx.is_file():
        return None, ["no junit.xml was written: pytest did not start (see runner-output.log)"]
    tests = []
    out_dir = exec_dir / "test-output"
    art = {p.name: p for p in out_dir.iterdir()} if out_dir.is_dir() else {}
    for tc_el in ET.parse(jx).getroot().iter("testcase"):
        name, cls = tc_el.get("name", ""), tc_el.get("classname", "")
        full = f"{cls}::{name}"
        fail = tc_el.find("failure") if tc_el.find("failure") is not None else tc_el.find("error")
        skip = tc_el.find("skipped")
        outcome = "failed" if fail is not None else "skipped" if skip is not None else "passed"
        msg = ((fail.get("message") or "") + "\n" + (fail.text or "")) if fail is not None else ""
        tc = TC_RE.search(full.replace("_", "-").upper())
        tc = tc.group(1) if tc else None
        base = f"{tc or 'NO-TC'}__{slug(name, 40)}"
        ev = {"screenshots": [], "traces": [], "videos": [], "browser_logs": [], "other": []}
        key_slug = slug(name).lower()
        for dname, p in art.items():  # pytest-playwright: test-output/<module>-py-<test-name>-<browser>/
            if key_slug and key_slug in slug(dname).lower():
                for n, f in enumerate(sorted(p.rglob("*")), 1):
                    if f.is_file():
                        key = "screenshots" if f.suffix == ".png" else "traces" if f.suffix == ".zip" else "videos" if f.suffix == ".webm" else "other"
                        dst = d / ("screenshots" if key == "screenshots" else "traces") / f"exec-{k:02d}"
                        dst.mkdir(parents=True, exist_ok=True)
                        tgt = dst / f"{base}__{n}{f.suffix}"
                        shutil.copyfile(f, tgt)
                        ev[key].append(rel(d, tgt))
        tests.append({"test_case": tc, "title": full, "file": tc_el.get("file") or cls.replace(".", "/") + ".py", "line": tc_el.get("line"),
                      "project": None, "outcome": outcome, "runner_status": outcome, "duration_ms": int(float(tc_el.get("time", 0)) * 1000),
                      "error": msg.strip()[:4000] or None, "failure_hint": hint(msg) if outcome == "failed" else None,
                      "annotations": [], "evidence": ev})
    return tests, []


def attach_console_logs(d, tests, k):
    """Python fixture writes logs/browser/exec-k/<slug>.json files; link them to their tests by name."""
    bdir = d / "logs" / "browser" / f"exec-{k:02d}"
    if not bdir.is_dir():
        return
    for f in bdir.glob("*.json"):
        for t in tests:
            if rel(d, f) not in t["evidence"]["browser_logs"] and f.stem.lower() == slug(t["title"].split("::")[-1]).lower():
                t["evidence"]["browser_logs"].append(rel(d, f))


def totals(tests):
    tot = {"total": len(tests)}
    for o in ("passed", "failed", "flaky", "skipped", "blocked"):
        tot[o] = sum(1 for t in tests if t["outcome"] == o)
    return tot


def merge_summary(d, execution, tests):
    sp = d / "results" / "summary.json"
    s = json.loads(sp.read_text(encoding="utf-8")) if sp.is_file() else {"executions": [], "tests": []}
    s["executions"].append(execution)
    # A test renamed while fixing it would otherwise leave its old result behind: results for a test case that this
    # execution re-ran (same TC, file and project, different title) are moved to "superseded", not deleted.
    rerun = {(t["test_case"], t.get("file"), t.get("project")) for t in tests if t.get("test_case")}
    titles = {(t["title"], t.get("project")) for t in tests}
    keep, superseded = [], s.setdefault("superseded", [])
    for t in s["tests"]:
        if (t.get("test_case"), t.get("file"), t.get("project")) in rerun and (t["title"], t.get("project")) not in titles:
            superseded.append({**t, "superseded_by": execution["id"]})
        else:
            keep.append(t)
    s["tests"] = keep
    by_key = {(t["title"], t.get("project")): t for t in s["tests"]}
    for t in tests:
        by_key[(t["title"], t.get("project"))] = {**t, "execution": execution["id"]}
    s["tests"] = sorted(by_key.values(), key=lambda t: (t.get("test_case") or "ZZZ", t["title"]))
    s["totals"] = totals(s["tests"])
    tcs = {}
    order = {"failed": 0, "blocked": 1, "flaky": 2, "passed": 3, "skipped": 4}
    for t in s["tests"]:
        if t.get("test_case"):
            cur = tcs.get(t["test_case"])
            if cur is None or order[t["outcome"]] < order[cur]:
                tcs[t["test_case"]] = t["outcome"]
    s["test_cases"] = dict(sorted(tcs.items()))
    s["updated_at"] = now()
    sp.write_text(json.dumps(s, indent=2), encoding="utf-8")
    return s


def spec_hashes(wt, tests, specs):
    files = sorted({t["file"] for t in tests if t.get("file")} | set(specs or []))
    res = {}
    for f in files:
        for cand in (wt / f, *(p for p in wt.rglob(Path(f).name) if "node_modules" not in p.parts)):
            if cand.is_file():
                res[cand.relative_to(wt).as_posix()] = hashlib.sha256(cand.read_bytes()).hexdigest()
                break
    return res


def cmd_run(a):
    d = run_dir(a.run)
    wt = Path(a.cwd).expanduser().resolve()
    meta = load_meta(d)
    if not meta.get("app", {}).get("ready"):
        return out({"error": "the app is not recorded as ready (app_runner.py start); a validation without a running app is Blocked, not run",
                    "blocker": meta.get("app", {}).get("blocker")}, 2)
    runner = a.runner or ("python" if not (wt / "package.json").is_file() and not (wt / "e2e" / "package.json").is_file() else "node")
    k, name = next_exec(d, a.label)
    exec_dir = d / "results" / name
    exec_dir.mkdir(parents=True)
    label_dir = {"browser": d / "logs" / "browser" / f"exec-{k:02d}"}
    label_dir["browser"].mkdir(parents=True, exist_ok=True)
    cmd, code, secs, log = (node_run if runner == "node" else python_run)(a, d, wt, exec_dir, label_dir)
    tests, errors = (collect_node if runner == "node" else collect_python)(d, exec_dir, k)
    if tests is None or (not tests and code not in (0, 1)):
        reason = (errors or ["no tests ran"])[0]
        merge_meta(d, {"tests": {"execution_error": {"exec": name, "exit_code": code, "reason": reason, "log": rel(d, log)}}})
        log_event(d, {"event": "tests_not_executed", "exec": name, "exit_code": code, "reason": reason})
        full = log.read_text(encoding="utf-8", errors="replace")
        tail = "\n".join(full.splitlines()[-30:])
        fix = next((h for pat, h in RUNNER_HINTS if re.search(pat, full)), None)
        return out({"status": "NOT EXECUTED", "exit_code": code, "reason": reason, "runner_log": str(log), "log_tail": tail,
                    "likely_fix": fix, "next": "classify: environment (browsers/deps missing) or test-automation (config/syntax)"}, 4)
    attach_console_logs(d, tests, k)
    ver = run(["npx", "--no-install", "playwright", "--version"], cwd=str(wt))[1].strip() if runner == "node" else \
        run([sys.executable, "-c", "import importlib.metadata as m; print('playwright', m.version('playwright'))"], cwd=str(wt))[1].strip()
    execution = {"id": name, "label": a.label, "runner": runner, "command": " ".join(cmd), "exit_code": code, "seconds": secs,
                 "started_at": now(), "base_url": a.base_url, "grep": a.grep, "specs": a.specs, "projects": a.project,
                 "runner_log": rel(d, log), "global_errors": errors, "totals": totals(tests), "playwright_version": ver}
    s = merge_summary(d, execution, tests)
    hashes = spec_hashes(wt, tests, a.specs)
    merge_meta(d, {"tests": {"runner": runner, "totals": s["totals"], "test_cases": s["test_cases"], "executions": len(s["executions"]),
                             "execution_error": None},
                   "environment": {"playwright": ver, "base_url": a.base_url},
                   "committed_artifacts": {"spec_sha256": {**load_meta(d).get("committed_artifacts", {}).get("spec_sha256", {}), **hashes}}})
    log_event(d, {"event": "tests_executed", "exec": name, "exit_code": code, "totals": execution["totals"]})
    failed = [{"test_case": t["test_case"], "title": t["title"], "hint": t["failure_hint"], "error": (t["error"] or "")[:300],
               "evidence": t["evidence"]} for t in tests if t["outcome"] in ("failed", "blocked")]
    return out({"status": "EXECUTED", "exec": name, "exit_code": code, "totals": execution["totals"],
                "untraced_tests": [t["title"] for t in tests if not t["test_case"]], "failures": failed,
                "summary": str(d / "results" / "summary.json")})


def cmd_summary(a):
    d = run_dir(a.run)
    sp = d / "results" / "summary.json"
    if not sp.is_file():
        return out({"error": "no tests executed in this run yet"}, 2)
    s = json.loads(sp.read_text(encoding="utf-8"))
    if not a.markdown:
        return out(s)
    rows = ["| Test case | Test | Project | Result | Duration | Evidence |", "|---|---|---|---|---:|---|"]
    for t in s["tests"]:
        ev = t["evidence"]
        pre = a.link_prefix
        links = [f"[screenshot]({pre}{p})" for p in ev["screenshots"][:2]] + [f"[trace]({pre}{p})" for p in ev["traces"][:1]] + \
                [f"[console]({pre}{p})" for p in ev["browser_logs"][:1]]
        rows.append(f"| {t.get('test_case') or '—'} | {t['title'].replace('|', '/')} | {t.get('project') or ''} | {t['outcome']} | "
                    f"{(t.get('duration_ms') or 0) / 1000:.1f}s | {', '.join(links)} |")
    tot = s["totals"]
    print(f"**Totals:** {tot['total']} tests: {tot['passed']} passed, {tot['failed']} failed, {tot['blocked']} blocked, "
          f"{tot['skipped']} skipped, {tot['flaky']} flaky (executions: {len(s['executions'])})\n")
    print("\n".join(rows))
    return 0


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    p = sub.add_parser("run")
    p.add_argument("--run", required=True); p.add_argument("--cwd", required=True); p.add_argument("--base-url", required=True)
    p.add_argument("--runner", choices=("node", "python")); p.add_argument("--config"); p.add_argument("--test-dir")
    p.add_argument("--project", action="append"); p.add_argument("--grep"); p.add_argument("--label", default="initial")
    p.add_argument("--timeout", type=int, default=1800); p.add_argument("--python")
    p.add_argument("specs", nargs="*")
    p = sub.add_parser("summary"); p.add_argument("--run", required=True); p.add_argument("--markdown", action="store_true")
    p.add_argument("--link-prefix", default="../", help="prefix for evidence links; ../ suits report/validation-report.md")
    a = ap.parse_args()
    return cmd_run(a) if a.cmd == "run" else cmd_summary(a)


if __name__ == "__main__":
    sys.exit(main())
